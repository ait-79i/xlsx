// Scripts and files that load mapped tables into a database (see dbMapping.js for the mapping).
import { DIALECTS as BASE } from "./sqlGenerator";
import { orderedTables } from "./dbMapping";

const escapeString = (s) => `'${s.replace(/'/g, "''")}'`;
const quoteWith = (open, close = open) => (name) => `${open}${String(name).split(close).join(close + close)}${close}`;

const SQL = {
	postgres: { ...BASE.postgres, label: "PostgreSQL" },
	mysql: { ...BASE.mysql, label: "MySQL" },
	mariadb: { ...BASE.mysql, label: "MariaDB" },
	sqlite: BASE.sqlite,
	sqlserver: BASE.sqlserver,
	oracle: {
		label: "Oracle",
		quote: quoteWith('"'),
		types: {
			integer: "NUMBER(10)",
			bigint: "NUMBER(19)",
			float: "BINARY_DOUBLE",
			decimal: "NUMBER(18, 4)",
			boolean: "NUMBER(1)",
			date: "DATE",
			datetime: "TIMESTAMP",
			string: (length) => `VARCHAR2(${length} CHAR)`,
			text: "CLOB",
			json: "CLOB",
		},
		boolean: (v) => (v ? "1" : "0"),
		string: escapeString,
		tableSuffix: "",
	},
};

/** Every database the page can load into, by family. */
export const TARGETS = {
	postgres: { family: "sql", label: "PostgreSQL", namespace: "schema" },
	mysql: { family: "sql", label: "MySQL", namespace: "database" },
	mariadb: { family: "sql", label: "MariaDB", namespace: "database" },
	sqlite: { family: "sql", label: "SQLite", namespace: null },
	sqlserver: { family: "sql", label: "SQL Server", namespace: "schema" },
	oracle: { family: "sql", label: "Oracle", namespace: "schema" },
	mongodb: { family: "mongo", label: "MongoDB", namespace: "database" },
	cassandra: { family: "cql", label: "Cassandra", namespace: "keyspace" },
	elasticsearch: { family: "es", label: "Elasticsearch", namespace: null },
};

export const MODES = ["insert", "upsert", "skip"];

const chunk = (list, size) => {
	const out = [];
	for (let i = 0; i < list.length; i += size) out.push(list.slice(i, i + size));
	return out;
};

const stamp = (target, built) => {
	const rows = built.reduce((n, b) => n + b.rows.length, 0);
	return `Generated by XLSX for ${TARGETS[target].label}: ${built.length} table(s), ${rows} row(s)`;
};

// ------------------------------------------------------------------ SQL

function sqlLiteral(value, column, d, target) {
	if (value === null || value === undefined) return "NULL";
	if (typeof value === "boolean") return d.boolean(value);
	if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
	if (typeof value === "object") return d.string(JSON.stringify(value));
	const text = String(value);
	if (target === "oracle" && column.type === "date" && /^\d{4}-\d{2}-\d{2}$/.test(text)) return `DATE '${text}'`;
	if (target === "oracle" && column.type === "datetime") return `TIMESTAMP '${text.replace("T", " ").replace(/Z$/, "")}'`;
	return d.string(text);
}

const columnType = (column, d) => {
	const type = d.types[column.type] ?? d.types.string;
	return typeof type === "function" ? type(255) : type;
};

function createTable(table, d, target, name) {
	const q = d.quote;
	const keys = table.columns.filter((c) => c.key);
	const lines = table.columns.map((c) => `  ${q(c.name)} ${columnType(c, d)}${c.key ? " NOT NULL" : ""}`);
	if (keys.length) lines.push(`  PRIMARY KEY (${keys.map((c) => q(c.name)).join(", ")})`);
	const body = `(\n${lines.join(",\n")}\n)${d.tableSuffix ?? ""}`;
	if (target === "sqlserver") {
		const plain = name.replace(/[[\]]/g, "");
		return `IF OBJECT_ID(N'${plain.replace(/'/g, "''")}', N'U') IS NULL\nCREATE TABLE ${name} ${body};`;
	}
	if (target === "oracle") {
		// Oracle has no IF NOT EXISTS: ignore "name already used" (ORA-00955)
		const ddl = `CREATE TABLE ${name} ${body}`.replace(/'/g, "''");
		return `BEGIN\n  EXECUTE IMMEDIATE '${ddl}';\nEXCEPTION\n  WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;\nEND;\n/`;
	}
	return `CREATE TABLE IF NOT EXISTS ${name} ${body};`;
}

function insertStatements(table, rows, d, target, name, { mode, batchSize }) {
	if (rows.length === 0) return [];
	const q = d.quote;
	const cols = table.columns.map((c) => q(c.name)).join(", ");
	const keys = table.columns.filter((c) => c.key);
	const others = table.columns.filter((c) => !c.key);
	const values = (row) => `(${row.map((v, i) => sqlLiteral(v, table.columns[i], d, target)).join(", ")})`;
	const effective = keys.length === 0 ? "insert" : mode;
	const out = [];
	if (effective !== mode) out.push(`-- ${table.name}: no key column, so rows are simply inserted`);

	// SQL Server accepts at most 1000 rows per VALUES list
	const size = target === "sqlserver" ? Math.min(batchSize, 1000) : batchSize;
	for (const batch of chunk(rows, size)) {
		if (target === "sqlserver" || target === "oracle") {
			if (effective === "insert") {
				out.push(target === "oracle"
					? `INSERT ALL\n${batch.map((r) => `  INTO ${name} (${cols}) VALUES ${values(r)}`).join("\n")}\nSELECT 1 FROM DUAL;`
					: `INSERT INTO ${name} (${cols}) VALUES\n${batch.map(values).join(",\n")};`);
				continue;
			}
			const source = target === "oracle"
				? `(\n${batch.map((r) => `  SELECT ${r.map((v, i) => `${sqlLiteral(v, table.columns[i], d, target)} AS ${q(table.columns[i].name)}`).join(", ")} FROM DUAL`).join(" UNION ALL\n")}\n) s`
				: `(VALUES\n${batch.map(values).join(",\n")}\n) AS s (${cols})`;
			const on = keys.map((k) => `t.${q(k.name)} = s.${q(k.name)}`).join(" AND ");
			const update = effective === "upsert" && others.length
				? `\nWHEN MATCHED THEN UPDATE SET ${others.map((c) => `t.${q(c.name)} = s.${q(c.name)}`).join(", ")}`
				: "";
			out.push(`MERGE INTO ${name} ${target === "oracle" ? "t" : "AS t"}\nUSING ${source}\nON (${on})${update}\nWHEN NOT MATCHED THEN INSERT (${cols}) VALUES (${table.columns.map((c) => `s.${q(c.name)}`).join(", ")});`);
			continue;
		}

		const rowsSql = batch.map(values).join(",\n");
		const keyList = keys.map((k) => q(k.name)).join(", ");
		if (target === "mysql" || target === "mariadb") {
			if (effective === "skip") out.push(`INSERT IGNORE INTO ${name} (${cols}) VALUES\n${rowsSql};`);
			else if (effective === "upsert" && others.length) {
				// MariaDB keeps VALUES(); MySQL 8 names the new row instead
				const set = others.map((c) => (target === "mysql" ? `${q(c.name)} = new.${q(c.name)}` : `${q(c.name)} = VALUES(${q(c.name)})`)).join(", ");
				out.push(`INSERT INTO ${name} (${cols}) VALUES\n${rowsSql}${target === "mysql" ? " AS new" : ""}\nON DUPLICATE KEY UPDATE ${set};`);
			} else out.push(`INSERT${effective === "upsert" ? " IGNORE" : ""} INTO ${name} (${cols}) VALUES\n${rowsSql};`);
			continue;
		}
		// PostgreSQL, SQLite
		let conflict = "";
		if (effective === "skip" || (effective === "upsert" && !others.length)) conflict = `\nON CONFLICT (${keyList}) DO NOTHING`;
		else if (effective === "upsert") conflict = `\nON CONFLICT (${keyList}) DO UPDATE SET ${others.map((c) => `${q(c.name)} = excluded.${q(c.name)}`).join(", ")}`;
		out.push(`INSERT INTO ${name} (${cols}) VALUES\n${rowsSql}${conflict};`);
	}
	return out;
}

const TRANSACTION = {
	postgres: ["BEGIN;", "COMMIT;"],
	mysql: ["START TRANSACTION;", "COMMIT;"],
	mariadb: ["START TRANSACTION;", "COMMIT;"],
	sqlite: ["BEGIN TRANSACTION;", "COMMIT;"],
	sqlserver: ["BEGIN TRANSACTION;", "COMMIT TRANSACTION;"],
	oracle: ["", "COMMIT;"],
};

/** A SQL script creating the tables (optional) and loading the rows. */
export function sqlScript(built, target, { createTables = true, mode = "insert", transaction = true, batchSize = 500, namespace = "" } = {}) {
	const d = SQL[target];
	const qualified = (table) => (namespace.trim() ? `${d.quote(namespace.trim())}.${d.quote(table.name)}` : d.quote(table.name));
	const ordered = orderedTables({ tables: built.map((b) => b.table) }).map((t) => built.find((b) => b.table === t));
	const parts = [`-- ${stamp(target, built)}`];
	if (createTables) ordered.forEach(({ table }) => parts.push(createTable(table, d, target, qualified(table))));
	const [begin, commit] = TRANSACTION[target];
	if (transaction && begin) parts.push(begin);
	ordered.forEach(({ table, rows }) => {
		if (rows.length) parts.push(`-- ${table.name}: ${rows.length} row(s)`);
		parts.push(...insertStatements(table, rows, d, target, qualified(table), { mode, batchSize }));
	});
	if (transaction || target === "oracle") parts.push(commit);
	return parts.join("\n\n") + "\n";
}

// ------------------------------------------------------------------ CSV files

const csvCell = (v) => {
	if (v === null || v === undefined) return "";
	const text = typeof v === "object" ? JSON.stringify(v) : String(v);
	return /[",\r\n]/.test(text) || /^\s|\s$/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
};

/** One CSV file per table (header row, then the rows). */
export const csvFiles = (built) =>
	built.map(({ table, rows }) => ({
		name: `${table.name}.csv`,
		mime: "text/csv",
		content: [table.columns.map((c) => csvCell(c.name)), ...rows.map((r) => r.map(csvCell))].map((r) => r.join(",")).join("\r\n") + "\r\n",
	}));

/** The command importing each CSV file, for the database's own tools. */
export function csvCommands(built, target, { namespace = "" } = {}) {
	return built.map(({ table }) => {
		const file = `${table.name}.csv`;
		const name = namespace.trim() ? `${namespace.trim()}.${table.name}` : table.name;
		const cols = table.columns.map((c) => c.name).join(", ");
		switch (target) {
			case "postgres":
				return `\\copy ${name} (${cols}) FROM '${file}' WITH (FORMAT csv, HEADER true)`;
			case "mysql":
			case "mariadb":
				return `LOAD DATA LOCAL INFILE '${file}' INTO TABLE ${name}\n  FIELDS TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"'\n  LINES TERMINATED BY '\\r\\n' IGNORE 1 LINES (${cols});`;
			case "sqlite":
				return `.import --csv --skip 1 ${file} ${table.name}`;
			case "sqlserver":
				return `BULK INSERT ${name} FROM 'C:\\data\\${file}'\n  WITH (FORMAT = 'CSV', FIRSTROW = 2, CODEPAGE = '65001');`;
			case "oracle":
				return `sqlldr userid=USER/PASSWORD control=${table.name}.ctl\n-- ${table.name}.ctl:\n-- OPTIONS (SKIP=1) LOAD DATA INFILE '${file}' APPEND INTO TABLE ${name}\n-- FIELDS TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"' TRAILING NULLCOLS (${cols})`;
			case "cassandra":
				return `COPY ${name} (${cols}) FROM '${file}' WITH HEADER = true;`;
			default:
				return "";
		}
	}).filter(Boolean).join("\n\n") + "\n";
}

// ------------------------------------------------------------------ MongoDB

const isDateType = (c) => c.type === "date" || c.type === "datetime";
const isoDate = (v) => (/^\d{4}-\d{2}-\d{2}$/.test(v) ? `${v}T00:00:00Z` : v);

/** Rows -> documents; a column named "address.city" makes a nested document. */
function documents(table, rows, dateValue) {
	return rows.map((row) => {
		const doc = {};
		table.columns.forEach((c, i) => {
			let v = row[i];
			if (v === null || v === undefined) return;
			if (isDateType(c) && typeof v === "string") v = dateValue(isoDate(v));
			const path = c.name.split(".");
			let target = doc;
			path.slice(0, -1).forEach((k) => { target = target[k] = target[k] && typeof target[k] === "object" ? target[k] : {} });
			target[path[path.length - 1]] = v;
		});
		return doc;
	});
}

const DATE_MARK = "@@xlsx-date@@";

/** A mongosh script: insertMany, or bulkWrite upserts on the key columns. */
export function mongoScript(built, { mode = "insert", batchSize = 1000, namespace = "" } = {}) {
	const lines = [`// ${stamp("mongodb", built)}`, `// Run with: mongosh "mongodb://HOST:27017" ${namespace.trim() ? "" : "DATABASE "}load.js`];
	if (namespace.trim()) lines.push(`db = db.getSiblingDB(${JSON.stringify(namespace.trim())});`);
	for (const { table, rows } of built) {
		const keys = table.columns.filter((c) => c.key).map((c) => c.name);
		const docs = documents(table, rows, (v) => `${DATE_MARK}${v}`);
		// dates become new Date("…") in the script
		const toJs = (value) => JSON.stringify(value).replace(new RegExp(`"${DATE_MARK}([^"]*)"`, "g"), 'new Date("$1")');
		const coll = `db.getCollection(${JSON.stringify(table.name)})`;
		lines.push(`\n// ${table.name}: ${docs.length} document(s)`);
		const effective = keys.length === 0 ? "insert" : mode;
		if (effective !== mode) lines.push(`// no key column: documents are simply inserted`);
		for (const batch of chunk(docs, batchSize)) {
			if (effective === "insert") {
				lines.push(`${coll}.insertMany([\n${batch.map((d) => `  ${toJs(d)}`).join(",\n")}\n], { ordered: false });`);
			} else {
				const ops = batch.map((d) => {
					const filter = Object.fromEntries(keys.map((k) => [k, d[k] ?? null]));
					const update = effective === "upsert" ? { $set: d } : { $setOnInsert: d };
					return `  { updateOne: { filter: ${toJs(filter)}, update: ${toJs(update)}, upsert: true } }`;
				});
				lines.push(`${coll}.bulkWrite([\n${ops.join(",\n")}\n], { ordered: false });`);
			}
		}
	}
	return lines.join("\n") + "\n";
}

/** One file per collection for mongoimport: one document per line, dates in Extended JSON. */
export const mongoFiles = (built) =>
	built.map(({ table, rows }) => ({
		name: `${table.name}.json`,
		mime: "application/x-ndjson",
		content: documents(table, rows, (v) => ({ $date: v })).map((d) => JSON.stringify(d)).join("\n") + "\n",
	}));

export function mongoCommands(built, { mode = "insert", namespace = "" } = {}) {
	return built.map(({ table }) => {
		const keys = table.columns.filter((c) => c.key).map((c) => c.name);
		const upsert = mode !== "insert" && keys.length ? ` --mode=${mode === "upsert" ? "upsert" : "insert"} --upsertFields=${keys.join(",")}` : "";
		return `mongoimport --uri "mongodb://HOST:27017/${namespace.trim() || "DATABASE"}" --collection ${table.name} --file ${table.name}.json${upsert}`;
	}).join("\n") + "\n";
}

// ------------------------------------------------------------------ Cassandra

const CQL_TYPES = { integer: "int", bigint: "bigint", float: "double", decimal: "decimal", boolean: "boolean", date: "date", datetime: "timestamp", string: "text", text: "text", json: "text" };
const cqlQuote = quoteWith('"');

function cqlLiteral(v) {
	if (v === null || v === undefined) return "null";
	if (typeof v === "boolean") return v ? "true" : "false";
	if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
	if (typeof v === "object") return escapeString(JSON.stringify(v));
	return escapeString(String(v));
}

/** CQL: CREATE TABLE IF NOT EXISTS and INSERT (an insert replaces a row with the same key in Cassandra). */
export function cqlScript(built, { createTables = true, mode = "upsert", batchSize = 50, namespace = "" } = {}) {
	const name = (t) => (namespace.trim() ? `${cqlQuote(namespace.trim())}.${cqlQuote(t.name)}` : cqlQuote(t.name));
	const parts = [`-- ${stamp("cassandra", built)}`];
	for (const { table, rows } of built) {
		const keys = table.columns.filter((c) => c.key);
		// Cassandra requires a primary key: the first column when none is marked
		const pk = (keys.length ? keys : table.columns.slice(0, 1)).map((c) => cqlQuote(c.name));
		if (createTables) {
			const cols = table.columns.map((c) => `  ${cqlQuote(c.name)} ${CQL_TYPES[c.type] ?? "text"}`);
			parts.push(`CREATE TABLE IF NOT EXISTS ${name(table)} (\n${cols.join(",\n")},\n  PRIMARY KEY (${pk.join(", ")})\n);`);
		}
		const cols = table.columns.map((c) => cqlQuote(c.name)).join(", ");
		const insert = (r) => `INSERT INTO ${name(table)} (${cols}) VALUES (${r.map(cqlLiteral).join(", ")})${mode === "skip" ? " IF NOT EXISTS" : ""};`;
		if (mode === "skip") rows.forEach((r) => parts.push(insert(r)));
		else chunk(rows, batchSize).forEach((batch) => parts.push(`BEGIN UNLOGGED BATCH\n${batch.map((r) => `  ${insert(r)}`).join("\n")}\nAPPLY BATCH;`));
	}
	return parts.join("\n\n") + "\n";
}

// ------------------------------------------------------------------ Elasticsearch

const ES_TYPES = { integer: "integer", bigint: "long", float: "double", decimal: "double", boolean: "boolean", date: "date", datetime: "date", string: "keyword", text: "text", json: "object" };

/** Bulk API body (NDJSON): one action line and one document line per row. */
export function esBulk(built, { mode = "insert", namespace = "" } = {}) {
	const lines = [];
	for (const { table, rows } of built) {
		const index = `${namespace.trim()}${table.name}`;
		const keys = table.columns.filter((c) => c.key).map((c) => c.name);
		for (const doc of documents(table, rows, (v) => v)) {
			const id = keys.length ? keys.map((k) => doc[k]).join("_") : undefined;
			const action = mode === "skip" && id !== undefined ? "create" : "index";
			lines.push(JSON.stringify({ [action]: { _index: index, ...(id !== undefined ? { _id: String(id) } : {}) } }));
			lines.push(JSON.stringify(doc));
		}
	}
	return lines.join("\n") + "\n";
}

export function esCommands(built, { namespace = "" } = {}) {
	const mappings = built.map(({ table }) => {
		const properties = Object.fromEntries(table.columns.filter((c) => !c.name.includes(".")).map((c) => [c.name, { type: ES_TYPES[c.type] ?? "keyword" }]));
		return `curl -X PUT "$ES_URL/${namespace.trim()}${table.name}" -H "Content-Type: application/json" -d '${JSON.stringify({ mappings: { properties } })}'`;
	});
	return [
		"# Optional: create the indexes with their field types first",
		...mappings,
		"",
		"# Then send the documents",
		`curl -X POST "$ES_URL/_bulk" -H "Content-Type: application/x-ndjson" --data-binary @bulk.ndjson`,
	].join("\n") + "\n";
}

// ------------------------------------------------------------------ one entry point

/**
 * What the page offers to download for a target and an output ("script" or "files").
 * @returns {{ files: { name, mime, content }[], commands?: string }}
 */
export function generate(built, target, output, options = {}) {
	const family = TARGETS[target].family;
	if (family === "sql") {
		if (output === "files") return { files: csvFiles(built), commands: csvCommands(built, target, options) };
		return { files: [{ name: "load.sql", mime: "application/sql", content: sqlScript(built, target, options) }] };
	}
	if (family === "mongo") {
		if (output === "files") return { files: mongoFiles(built), commands: mongoCommands(built, options) };
		return { files: [{ name: "load.js", mime: "text/javascript", content: mongoScript(built, options) }] };
	}
	if (family === "cql") {
		if (output === "files") return { files: csvFiles(built), commands: csvCommands(built, "cassandra", options) };
		return { files: [{ name: "load.cql", mime: "text/plain", content: cqlScript(built, options) }] };
	}
	return { files: [{ name: "bulk.ndjson", mime: "application/x-ndjson", content: esBulk(built, options) }], commands: esCommands(built, options) };
}
